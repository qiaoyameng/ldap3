"""Command line interface: build plans and verify round trips against a mock DIT."""

from __future__ import annotations

import argparse
import copy
import json
import os
import sys
from typing import Any, Dict, List

from .ldif import parse_ldif_changes, write_ldif
from .mockdit import MockDIT, MockDITError, apply_change_records
from .planner import ChangePlanner, STATUS_BLOCKED, STATUS_INVALID, STATUS_REVERSIBLE


def _load_json(path: str) -> Any:
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def load_snapshot(path: str) -> Dict[str, Dict[str, Any]]:
    data = _load_json(path)
    if isinstance(data, dict) and "entries" in data:
        snapshot: Dict[str, Dict[str, Any]] = {}
        for entry in data["entries"]:
            snapshot[entry["dn"]] = entry.get("attributes", entry.get("raw", {}))
        return snapshot
    if isinstance(data, dict):
        return data
    raise ValueError("snapshot must be a {dn: {attr: [values]}} object or "
                     "contain an 'entries' list")


def load_operations(path: str) -> List[Dict[str, Any]]:
    data = _load_json(path)
    if isinstance(data, dict):
        operations = data.get("operations", data.get("changes"))
    else:
        operations = data
    if not isinstance(operations, list):
        raise ValueError("operations file must contain a list of operations")
    return operations


def _forward_header(result) -> str:
    lines = [
        "Forward LDIF generated by ldifplan (plan only, not executed against a server).",
        "Apply reverse.ldif in order to compensate. Operations outside the reversible",
        "range are listed in plan_report.json and intentionally omitted here.",
    ]
    if not result.reversible:
        blocked = [op for op in result.operations if op.status != STATUS_REVERSIBLE]
        lines.append("WARNING: %d operation(s) are outside the reversible range:" % len(blocked))
        for op in blocked:
            lines.append("#   [%d] %s %s -- %s"
                         % (op.index, _op_type(op.operation), op.forward_dn or "", op.reason))
    return "\n".join(lines)


def _reverse_header(result) -> str:
    return (
        "Compensation LDIF generated by ldifplan.\n"
        "Records are already in reverse execution order and modDN compensation\n"
        "targets the entry address current at that point of the rollback."
    )


def _op_type(operation: Dict[str, Any]) -> str:
    return str(operation.get("operation", operation.get("type", "?"))).lower()


def cmd_plan(args: argparse.Namespace) -> int:
    snapshot = load_snapshot(args.snapshot)
    operations = load_operations(args.operations)
    planner = ChangePlanner(snapshot)
    result = planner.plan(operations)

    os.makedirs(args.outdir, exist_ok=True)
    forward_path = os.path.join(args.outdir, "forward.ldif")
    reverse_path = os.path.join(args.outdir, "reverse.ldif")
    report_path = os.path.join(args.outdir, "plan_report.json")

    write_ldif(forward_path, result.forward_records, _forward_header(result))
    write_ldif(reverse_path, result.reverse_records, _reverse_header(result))
    with open(report_path, "w", encoding="utf-8") as handle:
        json.dump(result.report(), handle, ensure_ascii=False, indent=2)

    counts = {STATUS_REVERSIBLE: 0, STATUS_INVALID: 0, STATUS_BLOCKED: 0}
    for op in result.operations:
        counts[op.status] = counts.get(op.status, 0) + 1
    print("plan written to %s" % args.outdir)
    print("  reversible: %d   invalid: %d   blocked: %d"
          % (counts[STATUS_REVERSIBLE], counts[STATUS_INVALID], counts[STATUS_BLOCKED]))
    for op in result.operations:
        if op.status != STATUS_REVERSIBLE:
            print("  [%d] %s %s: %s -- %s"
                  % (op.index, op.status, _op_type(op.operation),
                     op.forward_dn or "(unresolved dn)", op.reason))
    if result.verification_problems:
        print("ROUND-TRIP CHECK FAILED:", file=sys.stderr)
        for problem in result.verification_problems:
            print("  " + problem, file=sys.stderr)
        return 2
    print("round-trip check: PASS (reversible range restores the snapshot)")
    return 0


def cmd_verify(args: argparse.Namespace) -> int:
    snapshot = load_snapshot(args.snapshot)
    with open(args.forward, "r", encoding="utf-8") as handle:
        forward_records = parse_ldif_changes(handle.read())
    with open(args.reverse, "r", encoding="utf-8") as handle:
        reverse_records = parse_ldif_changes(handle.read())

    excluded = set()
    if args.report:
        report = _load_json(args.report)
        excluded.update(report.get("excluded_dns", []))

    original_dit = MockDIT(copy.deepcopy(snapshot))
    original = original_dit.snapshot_copy()

    forward_dit = MockDIT(copy.deepcopy(snapshot))
    try:
        apply_change_records(forward_dit, forward_records)
    except MockDITError as error:
        print("applying forward.ldif failed: %s" % error, file=sys.stderr)
        return 1
    post_forward = forward_dit.snapshot_copy()
    print("forward applied: %d -> %d entries" % (len(original), len(post_forward)))

    try:
        apply_change_records(forward_dit, reverse_records)
    except MockDITError as error:
        print("applying reverse.ldif failed: %s" % error, file=sys.stderr)
        return 1

    in_scope = lambda dn: not any(dn == excluded_dn or dn.startswith(excluded_dn + ",")
                                  for excluded_dn in excluded)
    problems: List[str] = []
    compared = 0
    for dn in sorted(dn for dn in set(original) | set(forward_dit.entries) if in_scope(dn)):
        if dn not in original:
            problems.append("extra entry: %s" % dn)
        elif dn not in forward_dit.entries:
            problems.append("missing entry: %s" % dn)
            continue
        compared += 1
        for attribute in sorted(set(original[dn]) | set(forward_dit.entries[dn])):
            if original[dn].get(attribute) != forward_dit.entries[dn].get(attribute):
                problems.append("values differ: %s of %s" % (attribute, dn))

    if problems:
        print("RESTORE CHECK FAILED:", file=sys.stderr)
        for problem in problems:
            print("  " + problem, file=sys.stderr)
        return 2
    if excluded:
        print("note: %d DN(s) outside the reversible range were not compared: %s"
              % (len(excluded), ", ".join(sorted(excluded))))
    print("restore check: PASS - reversible range restores the original entry set "
          "exactly (%d in-scope entries)" % compared)
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="ldifplan",
                                     description="Generate reversible LDIF change plans.")
    subparsers = parser.add_subparsers(dest="command", required=True)

    plan_parser = subparsers.add_parser("plan", help="build forward/reverse LDIF from snapshot + ops")
    plan_parser.add_argument("--snapshot", required=True)
    plan_parser.add_argument("--operations", required=True)
    plan_parser.add_argument("--outdir", required=True)
    plan_parser.set_defaults(func=cmd_plan)

    verify_parser = subparsers.add_parser("verify", help="apply forward then reverse to a mock DIT")
    verify_parser.add_argument("--snapshot", required=True)
    verify_parser.add_argument("--forward", required=True)
    verify_parser.add_argument("--reverse", required=True)
    verify_parser.add_argument("--report", help="plan_report.json used to determine "
                                               "DNs outside the reversible range")
    verify_parser.set_defaults(func=cmd_verify)
    return parser


def main(argv: List[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
